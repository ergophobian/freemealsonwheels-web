import puppeteer from 'puppeteer-core';
const [,, outDir, url = 'http://localhost:4321/'] = process.argv;
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--hide-scrollbars'] });
const p = await b.newPage();
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await p.setUserAgent('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1');
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(url, { waitUntil: 'networkidle0', timeout: 90000 }); await new Promise((r) => setTimeout(r, 7000));
let n = 0; const shot = async (name) => p.screenshot({ path: `${outDir}/m${String(++n).padStart(2, '0')}-${name}.png` });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const swipe = async (dx) => { await p.touchscreen.touchStart(200, 500); for (let i = 1; i <= 8; i++) await p.touchscreen.touchMove(200 + dx * i / 8, 505); await p.touchscreen.touchEnd(); };
const tapSel = async (sel) => { const el = await p.$(sel); const bx = await el.boundingBox(); await p.touchscreen.tap(bx.x + bx.width / 2, bx.y + bx.height / 2); };
await shot('home');
await swipe(-160); await wait(3200); await shot('swipe-1');
await tapSel('#labels button[data-station="volunteer"]').catch(() => {}); await wait(3800); await shot('volunteer-open');
await tapSel('#pop-close'); await wait(3000); await shot('closed');
await swipe(-160); await wait(2800); await swipe(-160); await wait(3200); await shot('swipe-2');
await tapSel('#labels button:not(.off)').catch(() => {}); await wait(3800); await shot('station-open');
console.log('errors', errs.slice(0, 5));
await b.close();
